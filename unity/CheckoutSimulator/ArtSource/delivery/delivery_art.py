def sheet(name, w, h, loc, m, nu=12, nv=12, rot=(0, 0, 0), fn=None, uv=(1, 1), uv2=False, solid=0., ss=0, smooth=True, solid_off=1):
    """Grid in the local XZ plane (normal -Y, centred), UV 0..1 (scaled by uv). fn(u, v, x, z) -> Vector moves each vertex.
    uv2 adds a second unscaled UV map "Print" (for logos on a tiled material). solid > 0 adds paper/fabric thickness."""
    bm = bmesh.new(); L = bm.loops.layers.uv.new("UVMap"); L2 = bm.loops.layers.uv.new("Print") if uv2 else None
    vs = {}
    for i in range(nu + 1):
        for j in range(nv + 1):
            u, v = i / nu, j / nv; x, z = (u - .5) * w, (v - .5) * h
            vs[i, j] = bm.verts.new(fn(u, v, x, z) if fn else Vector((x, 0, z)))
    for i in range(nu):
        for j in range(nv):
            f = bm.faces.new((vs[i, j], vs[i + 1, j], vs[i + 1, j + 1], vs[i, j + 1]))
            for lp, (a, b) in zip(f.loops, ((i, j), (i + 1, j), (i + 1, j + 1), (i, j + 1))):
                lp[L].uv = (a / nu * uv[0], b / nv * uv[1])
                if L2: lp[L2].uv = (a / nu, b / nv)
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(name, me); o.location = loc; o.rotation_euler = rot; _link(o); me.materials.append(m)
    if smooth:
        for p in me.polygons: p.use_smooth = True
    if solid:
        md = o.modifiers.new("solid", 'SOLIDIFY'); md.thickness = solid; md.offset = solid_off; md.use_even_offset = True
    if ss: B["subsurf"](o, ss)
    return o

def prof_extrude(name, prof, length, loc, m, rot=(0, 0, 0), bev=0., smooth=35):
    """Closed (y, z) profile extruded along local X (length centred) -> mouldings, nosings, sills, putty beads."""
    bm = bmesh.new(); a = [bm.verts.new((-length / 2, y, z)) for y, z in prof]; b = [bm.verts.new((length / 2, y, z)) for y, z in prof]
    n = len(prof)
    for k in range(n): bm.faces.new((a[k], a[(k + 1) % n], b[(k + 1) % n], b[k]))
    bm.faces.new(a[::-1]); bm.faces.new(b)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(name, me); o.location = loc; o.rotation_euler = rot; _link(o); me.materials.append(m)
    if bev: B["bevel"](o, bev, 2)
    _smooth(o, smooth); return o

def ucyl(name, r, h, loc, m, segs=48, rot=(0, 0, 0), uv=(1, 1), u0=0., arc=2 * PI, nv=1):
    """Open cylinder (label wrap) with u around / v up UVs."""
    bm = bmesh.new(); L = bm.loops.layers.uv.new("UVMap"); full = arc >= 2 * PI - 1e-6; cols = segs if full else segs + 1
    vs = [[bm.verts.new((r * math.cos(u0 + arc * i / segs), r * math.sin(u0 + arc * i / segs), h * j / nv)) for j in range(nv + 1)] for i in range(cols)]
    for i in range(segs):
        for j in range(nv):
            i2 = (i + 1) % cols
            f = bm.faces.new((vs[i][j], vs[i2][j], vs[i2][j + 1], vs[i][j + 1]))
            for lp, (a, b) in zip(f.loops, ((i, j), (i + 1, j), (i + 1, j + 1), (i, j + 1))): lp[L].uv = (a / segs * uv[0], b / nv * uv[1])
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(name, me); o.location = loc; o.rotation_euler = rot; _link(o); me.materials.append(m)
    for p in me.polygons: p.use_smooth = True
    return o

def disc(name, r, loc, m, rot=(0, 0, 0), segs=64):
    bm = bmesh.new(); L = bm.loops.layers.uv.new("UVMap"); c = bm.verts.new((0, 0, 0))
    ring = [bm.verts.new((r * math.cos(2 * PI * i / segs), r * math.sin(2 * PI * i / segs), 0)) for i in range(segs)]
    for i in range(segs):
        f = bm.faces.new((c, ring[i], ring[(i + 1) % segs]))
        for lp in f.loops: lp[L].uv = (lp.vert.co.x / (2 * r) + .5, lp.vert.co.y / (2 * r) + .5)
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(name, me); o.location = loc; o.rotation_euler = rot; _link(o); me.materials.append(m); return o

def multi_box(name, items, m, bev=0.):
    """Many small boxes in ONE mesh: items = [(size, loc, rot_z)] -> zipper teeth, grout, bars."""
    bm = bmesh.new()
    for size, loc, rz in items:
        g = bmesh.ops.create_cube(bm, size=1.)["verts"]
        mt = Matrix.Translation(loc) @ Matrix.Rotation(rz, 4, 'Z') @ Matrix.Diagonal((size[0], size[1], size[2], 1))
        bmesh.ops.transform(bm, matrix=mt, verts=g)
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(name, me); _link(o); me.materials.append(m)
    if bev: B["bevel"](o, bev, 2)
    return o

def sweep(name, path, radius_fn, m, sides=5, ridge=0., cap=True):
    """Tube swept along a polyline with a varying radius and optional ridged (polygonal) section -> bananas, cords."""
    bm = bmesh.new(); P = [Vector(p) for p in path]; rings = []
    for i, p in enumerate(P):
        t = (P[min(i + 1, len(P) - 1)] - P[max(i - 1, 0)]).normalized()
        n1 = t.cross(Vector((0, 0, 1))); n1 = n1.normalized() if n1.length > 1e-4 else Vector((1, 0, 0)); n2 = t.cross(n1)
        r = radius_fn(i / (len(P) - 1)); ring = []
        for k in range(sides * 3):
            a = 2 * PI * k / (sides * 3); rr = r * (1 + ridge * math.cos(a * sides))
            ring.append(bm.verts.new(p + (n1 * math.cos(a) + n2 * math.sin(a)) * rr))
        rings.append(ring)
    n = sides * 3
    for i in range(len(rings) - 1):
        for k in range(n): bm.faces.new((rings[i][k], rings[i][(k + 1) % n], rings[i + 1][(k + 1) % n], rings[i + 1][k]))
    if cap: bm.faces.new(rings[0][::-1]); bm.faces.new(rings[-1])
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(name, me); _link(o); me.materials.append(m)
    for p in me.polygons: p.use_smooth = True
    return o

class group:
    """with group("x", loc, rot): everything built inside is parented to an empty (loc/rot local to the outer group)."""
    def __init__(self, name, loc, rot=(0, 0, 0)): self.name, self.loc, self.rot = name, loc, rot
    def __enter__(self):
        bpy.ops.object.empty_add(location=self.loc, rotation=self.rot); e = bpy.context.object; e.name = self.name; e["layer"] = LAYER
        if B["ROOT"] is not None: e.parent = B["ROOT"]
        self.prev = B["ROOT"]; B["ROOT"] = e; return e
    def __exit__(self, *a): B["ROOT"] = self.prev

class layer:
    def __init__(self, name): self.name = name
    def __enter__(self):
        global LAYER; self.prev = LAYER; LAYER = self.name
    def __exit__(self, *a):
        global LAYER; LAYER = self.prev

