def _wrinkle(seed, amp=.003, freq=6.):
    def f(u, v, x, z, base=None):
        n = noise.noise(Vector((u * freq + seed, v * freq * 1.3, seed * .7))) + .5 * noise.noise(Vector((u * freq * 2.7, v * freq * 2.9 + seed, 1.3)))
        edge = math.sin(u * PI) ** .5 * math.sin(min(1, v * 1.15) * PI / 2)
        return amp * n * edge
    return f

def twisted_handle(nm, center, R, m, turns=9, r=.0028):
    pts = arc_pts(center, R, 4, 176, 80)
    for strand in range(2):
        P = []
        for i, p in enumerate(pts):
            t = i / (len(pts) - 1); a = rad(4 + 172 * t); T = Vector((-math.sin(a), 0, math.cos(a))); N1 = Vector((0, 1, 0)); N2 = T.cross(N1)
            ph = t * turns * 2 * PI + strand * PI
            P.append(Vector(p) + (N1 * math.cos(ph) + N2 * math.sin(ph)) * r * .9)
        curve_tube(f"{nm}_s{strand}", [tuple(q) for q in P], r, m, res=2, smooth=True)

def build_kraft_bag(logo=True, closed=False):
    """closed=True: the packed bag for the hand-over -- front and back pinched together at the top, the top rolled once and
    folded over the front as a flap (the customer sticker goes on it, see KRAFT_STICKER), no handles / receipt / sticker."""
    m = MA(); W, D, H = BAG["W"], BAG["D"], BAG["H"]; th = .0012
    wf = _wrinkle(1.7, .0035); wb = _wrinkle(4.2, .003); ws = _wrinkle(7.1, .0025)
    def folds(v): return -.0018 * sum(math.exp(-((v - c) / .012) ** 2) for c in (.25, .5, .75))   # flattening creases
    def pinch(v):                                     # 0 below the top band, 1 at the closed seam
        if not closed: return 0.
        t = min(1., max(0., (v - .78) / .22)); return t * t * (3 - 2 * t)
    TILT = math.sin(rad(4)) * H                       # the front panel leans 4 deg inward
    # back + gussets + bottom (back layer)
    sheet("kb_back", W, H, (0, D / 2, H / 2), m["kraft_d"], 40, 48, rot=(0, 0, rad(180)), fn=lambda u, v, x, z: Vector((x, wb(u, v, x, z) + folds(v) + pinch(v) * (D / 2 - .006), z)), solid=th)
    for s in (-1, 1):
        def side_fn(u, v, x, z, s=s):
            g = .03 * (1 - abs(2 * u - 1)) * (.55 + .45 * v)   # gusset folded inward
            p = pinch(v); g = g * (1 - p) + p * (D / 2) * .9 * (1 - abs(2 * u - 1))
            return Vector((x * (1 - .94 * p), g + ws(u, v, x, z) + folds(v) * .5, z))
        sheet(f"kb_side{s}", D, H, (s * W / 2, 0, H / 2), m["kraft"], 28, 48, rot=(0, 0, rad(90) * s), fn=side_fn, solid=th)
        if not closed: curve_tube(f"kb_crease{s}", [(s * (W / 2 - .03 * (.55 + .45 * k / 4)), 0, .01 + k * (H - .02) / 4) for k in range(5)], .0011, m["kraft_d"], res=3)
    box("kb_bottom", (W, D, .003), (0, 0, .0015), m["kraft_d"], bev=0)
    if not closed:
        box("kb_hem_back", (W - .004, .0015, .035), (0, D / 2 - .0022, H - .0175), m["kraft_d"], bev=0)
        box("kb_patch_back", (.11, .0015, .03), (0, D / 2 - .0035, H - .022), m["kraft"], bev=0)
        curve_tube("kb_rim_back", [(-W / 2, D / 2 - .0006, H), (W / 2, D / 2 - .0006, H)], .0012, m["kraft_d"], res=2, smooth=False)
        twisted_handle("kb_handle_b", (0, D / 2 - .004, H - .02), .075, m["kraft_d"])
    with layer("front"):
        with group("kb_front_grp", (0, -D / 2, 0), (rad(-4), 0, 0)):
            fm = m["kraft_p"] if logo else m["kraft"]
            sheet("kb_front", W, H, (0, 0, H / 2), fm, 40, 48, fn=lambda u, v, x, z: Vector((x, wf(u, v, x, z) + folds(v) + pinch(v) * (D / 2 - .006 - TILT), z)), solid=th)
            if not closed:
                box("kb_hem_front", (W - .004, .0015, .035), (0, .0022, H - .0175), m["kraft_d"], bev=0)
                box("kb_patch_front", (.11, .0015, .03), (0, .0035, H - .022), m["kraft"], bev=0)
                curve_tube("kb_rim_front", [(-W / 2, .0006, H), (W / 2, .0006, H)], .0012, m["kraft_d"], res=2, smooth=False)
                twisted_handle("kb_handle_f", (0, .004, H - .02), .075, m["kraft_d"])
                if logo:
                    with group("kb_receipt", (W / 2 - .07, -.006, H * .78), (0, rad(5), 0)):
                        sheet("kb_rc", .06, .12, (0, 0, -.05), m["receipt"], 4, 8, fn=lambda u, v, x, z: Vector((x, -.004 * (1 - v) ** 2, z)))
                        box("kb_staple", (.014, .002, .0015), (0, -.0015, .0), m["it_tin"], bev=.0005)
                    disc("kb_sticker", .022, (-W / 2 + .06, -.0045, H * .16), m["sticker1"], rot=(rad(90), 0, rad(12)), segs=40)
    if closed:
        with layer("front"):
            # rolled seam along the top + the folded flap hanging over the (pinched) front, following its surface
            Wc = W * .985; FL = KRAFT_FLAP
            cyl("kb_roll", .009, Wc, (0, -.004, H + .004), m["kraft_d"], axis='X', verts=24)
            def fy(z):                                 # world-ish y of the pinched front surface at height z (bag local)
                v = z / H; return -D / 2 + z * math.tan(rad(4)) + pinch(v) * (D / 2 - .006 - TILT)
            wfl = _wrinkle(9.3, .002, 9.)
