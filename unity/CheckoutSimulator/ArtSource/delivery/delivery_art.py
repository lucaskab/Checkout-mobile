def overlay(m, image, uv="UVMap", fac=1., blend='MIX', extension='REPEAT', rough=None):
    """Print an RGBA image over whatever feeds Base Color (the procedural colour/grain/bump stays)."""
    img = IMG(image)
    if img is None: return m
    nt = m.node_tree; b = [n for n in nt.nodes if n.type == 'BSDF_PRINCIPLED'][0]
    lk = [l for l in nt.links if l.to_socket == b.inputs["Base Color"]]
    src = lk[0].from_socket if lk else tuple(b.inputs["Base Color"].default_value)
    tx = nt.nodes.new("ShaderNodeTexImage"); tx.image = img; tx.extension = extension; tx.interpolation = 'Cubic'
    um = nt.nodes.new("ShaderNodeUVMap"); um.uv_map = uv; nt.links.new(um.outputs[0], tx.inputs[0])
    f = _M_(nt, 'MULTIPLY', tx.outputs["Alpha"], vb=fac)
    nt.links.new(_mix(nt, src, tx.outputs["Color"], f, blend), b.inputs["Base Color"])
    if rough is not None:
        lr = [l for l in nt.links if l.to_socket == b.inputs["Roughness"]]
        rs = lr[0].from_socket if lr else None
        mx = nt.nodes.new("ShaderNodeMix"); mx.data_type = 'FLOAT'
        if rs: nt.links.new(rs, mx.inputs[2])
        else: mx.inputs[2].default_value = b.inputs["Roughness"].default_value
        mx.inputs[3].default_value = rough; nt.links.new(f, mx.inputs[0]); nt.links.new(mx.outputs[0], b.inputs["Roughness"])
    return m

