def wood_mat(name, light, dark, scale=5., along='X', coat=.55, wear=.4, knots=1., rough=.42, pores=.5):
    """Varnished wood: noise-distorted bands stretched along the board (grain), pore streaks, voronoi knots with rings,
    bevel-node edge wear (lighter, rougher, varnish worn off), orange-peel varnish coat with smudged roughness."""
    if name in _P: return _P[name]
    m, nt, b, out = _new_mat(name)
    tc = nt.nodes.new("ShaderNodeTexCoord"); mp = _N(nt, "ShaderNodeMapping")
    mp.inputs["Scale"].default_value = (.12, 1, 1) if along == 'X' else (1, .12, 1) if along == 'Y' else (1, 1, .12)
    nt.links.new(tc.outputs["Object"], mp.inputs["Vector"]); v = mp.outputs["Vector"]
    dn = B["_noise"](nt, scale * .8, 4, .6); nt.links.new(v, dn.inputs["Vector"])
    vv = _N(nt, "ShaderNodeVectorMath", operation='ADD'); nt.links.new(v, vv.inputs[0])
    sc = _N(nt, "ShaderNodeVectorMath", operation='SCALE'); nt.links.new(dn.outputs["Color"], sc.inputs[0]); sc.inputs["Scale"].default_value = .35
    nt.links.new(sc.outputs[0], vv.inputs[1]); dv = vv.outputs[0]
    w = _N(nt, "ShaderNodeTexWave", Scale=scale, Distortion=3., Detail=4, **{"Detail Scale": 1.5}); w.wave_type = 'BANDS'
    w.bands_direction = 'Y' if along == 'X' else 'X' if along == 'Y' else 'X'; w.wave_profile = 'SAW'; nt.links.new(dv, w.inputs["Vector"])
    w2 = _N(nt, "ShaderNodeTexWave", Scale=scale * 3.1, Distortion=6., Detail=2); w2.wave_type = 'BANDS'; w2.bands_direction = w.bands_direction; nt.links.new(dv, w2.inputs["Vector"])
    grain = _M_(nt, 'ADD', _M_(nt, 'MULTIPLY', w.outputs["Fac"], vb=.7), _M_(nt, 'MULTIPLY', w2.outputs["Fac"], vb=.3))
    mp2 = _N(nt, "ShaderNodeMapping"); mp2.inputs["Scale"].default_value = (3, 120, 120) if along == 'X' else (120, 3, 120) if along == 'Y' else (120, 120, 3)
    nt.links.new(tc.outputs["Object"], mp2.inputs["Vector"]); pn = B["_noise"](nt, scale * 2, 2, .5); nt.links.new(mp2.outputs["Vector"], pn.inputs["Vector"])
    pore = _ramp2(nt, pn.outputs["Fac"], .58, .7)
    kv = _N(nt, "ShaderNodeTexVoronoi", Scale=scale * .35); nt.links.new(tc.outputs["Object"], kv.inputs["Vector"])
    km = _N(nt, "ShaderNodeMapRange"); km.inputs["From Min"].default_value = .04; km.inputs["From Max"].default_value = .16; km.inputs["To Min"].default_value = 1; km.inputs["To Max"].default_value = 0
    nt.links.new(kv.outputs["Distance"], km.inputs["Value"])
    rings = _M_(nt, 'ADD', _M_(nt, 'MULTIPLY', _M_(nt, 'SINE', _M_(nt, 'MULTIPLY', kv.outputs["Distance"], vb=160.)), vb=.5), vb=.5)
    knot = _M_(nt, 'MULTIPLY', _M_(nt, 'MULTIPLY', km.outputs[0], vb=knots), _M_(nt, 'ADD', rings, vb=.6))
    fac = _M_(nt, 'ADD', grain, knot); fac = _M_(nt, 'ADD', fac, _M_(nt, 'MULTIPLY', pore, vb=pores * .5))
    fac = _M_(nt, 'MAXIMUM', _M_(nt, 'MULTIPLY', _M_(nt, 'SUBTRACT', fac, vb=.22), vb=1.7), vb=0.)
