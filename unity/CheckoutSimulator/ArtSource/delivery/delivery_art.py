def export_steps():
    G = _groups(); S = G["static"]; st = []
    def backdrop():
        _vis(S); _render(_raw("backdrop"), transparent=False)
        _save(_load(_raw("backdrop")), os.path.join(GAME, "delivery_backdrop.jpg"), 'JPEG')
    st.append(("backdrop", backdrop))
    for key in ("kraft", "thermal"):
        def lay(key=key):
            bd = _bbox_screen([bpy.data.objects[n] for n in G[key]]); EXP[key + ":border"] = bd
            _vis(G[key + ":back"], S | G[key + ":front"]); _render(_raw(key + "_back"), bd)
            _vis(G[key + ":front"], S | G[key + ":back"]); _render(_raw(key + "_front"), bd)
            bw = _bbox_screen([bpy.data.objects[n] for n in G[key]], .075, .11); EXP[key + ":wide"] = bw
            _vis(S | G[key], ()); _render(_raw(key + "_full"), bw)
        def closed(key=key):
            k = key + "_closed"; bd = _bbox_screen([bpy.data.objects[n] for n in G[k]])
            _vis(G[k], S); _render(_raw(k), bd)
            bw = _bbox_screen([bpy.data.objects[n] for n in G[k]], .075, .11); EXP[k + ":wide"] = bw
            _vis(S | G[k], ()); _render(_raw(k + "_full"), bw)
        def compose(key=key):
            import numpy as np
            base = _load(_raw("backdrop")); back = _load(_raw(key + "_back")); front = _load(_raw(key + "_front"))
            sh = _shadow(_load(_raw(key + "_full")), base, np.maximum(back[..., 3], front[..., 3]), EXP.get(key + ":wide"))
            _save(_over_shadow(back, sh), os.path.join(GAME, f"bag_{key}_back.png")); _save(front, os.path.join(GAME, f"bag_{key}_front.png"))
            cl = _load(_raw(key + "_closed")); sh = _shadow(_load(_raw(key + "_closed_full")), base, cl[..., 3], EXP.get(key + "_closed:wide"))
            _save(_over_shadow(cl, sh), os.path.join(GAME, f"bag_{key}_closed.png"))
        st += [(key + "_layers", lay), (key + "_closed", closed), (key + "_compose", compose)]
    st.append(("layout", export_layout))
    def check():
        """composite check: backdrop + back + front (open bags, left/top) and backdrop + closed (right/bottom)."""
        import numpy as np
        def over(dst, src):
            a = src[..., 3:4]; dst[..., :3] = src[..., :3] * a + dst[..., :3] * (1 - a); return dst
        base = _load(_raw("backdrop")); base[..., 3] = 1
        op = base.copy(); cl = base.copy()
        for key in ("kraft", "thermal"):
            op = over(op, _load(os.path.join(GAME, f"bag_{key}_back.png"))); op = over(op, _load(os.path.join(GAME, f"bag_{key}_front.png")))
            cl = over(cl, _load(os.path.join(GAME, f"bag_{key}_closed.png")))
        _save(op, os.path.join(RAW, "check_open.png")); _save(cl, os.path.join(RAW, "check_closed.png"))
    st.append(("check", check))
    return st

def export_layers(only=None, samples=None, atomic=True):
    """Build the export scene, then render + compose from a bpy timer (the MCP call returns at once).  atomic=True runs every
    step inside ONE timer callback (another session cannot rebuild DeliveryArt in between); False = one step per tick."""
    os.makedirs(RAW, exist_ok=True); os.makedirs(GAME, exist_ok=True)
    state = dict(i=-1, done=[], t0=__import__("time").time()); _status_x(state="queued")
    def tick():
        import time, traceback
        try:
            sc_prev = bpy.context.window.scene if bpy.context.window else None
            if state["i"] < 0:
                _status_x(state="building"); build_export()
                if samples: bpy.data.scenes[SCENE].cycles.samples = samples
                state["steps"] = [s for s in export_steps() if only is None or s[0] in only or s[0] == "layout"]
                state["i"] = 0
                if not atomic: return .3
            while state["i"] < len(state["steps"]):
                name, fn = state["steps"][state["i"]]; _status_x(state="running", current=name, done=state["done"])
                t = time.time(); fn(); state["done"].append([name, round(time.time() - t, 1)]); state["i"] += 1
                if not atomic: break
            if bpy.context.window and sc_prev and bpy.context.window.scene != sc_prev: bpy.context.window.scene = sc_prev
            if state["i"] >= len(state["steps"]):
                for o in bpy.data.scenes[SCENE].objects: o.is_holdout = False
                _status_x(state="done", done=state["done"], secs=round(time.time() - state["t0"]), layout=export_layout()); return None
            return .3
        except Exception:
            _status_x(state="error", error=traceback.format_exc(), done=state["done"]); return None
    bpy.app.timers.register(tick, first_interval=.5)
    return "queued"

# ================================================================ BACKDROP WITH A TRANSPARENT WINDOW (live city view in Unity)
# delivery_backdrop.png (1920x1080 RGBA) = delivery_backdrop.jpg pixel for pixel, except that everything the camera sees through
# the glass (street, sky, cars, trees, facades, the parked motoboy, planters, the glass panes) is alpha 0.  Those objects keep
# "Visible to Camera" OFF only: they still cast shadows and bounce light, so the room is lit exactly as in the jpg.  Mullions,
# putty, sill, jambs and the wall stay opaque.  window_glass.png = white sheen, <= 13 % alpha, only inside the panes (optional).
# Bags, bag contents and loose groceries are not rendered.  The jpg is not touched.
#     export_backdrop_windowless()   # timer driven (MCP-safe); progress in render/export/backdrop_status.json (~2-3 min)
BACKDROP_PNG = os.path.join(GAME, "delivery_backdrop.png")
GLASS_PNG = os.path.join(GAME, "window_glass.png")
WIN_RECT = (0.2515, 0.5297, 0.7662, 0.9078)     # layout "window" (x0, y0, x1, y1), origin bottom-left
OUTSIDE_Y = .06                                  # objects whose whole bbox lies beyond the glass plane (y > .06) are the street

def _bstatus(**kw):
    os.makedirs(RAW, exist_ok=True)
    with open(os.path.join(RAW, "backdrop_status.json"), "w") as f: json.dump(kw, f, indent=1)

def _in_bag(o):
    while o is not None:
        if o.name.startswith("EXP_"): return True
        o = o.parent
    return False

def _backdrop_sets():
    """(all, outside): every static backdrop object (no bags, no groceries, no lights/camera), and the subset seen through
    the window = the street (anything whose bbox lies beyond the wall plane) plus the glass panes."""
    sc = bpy.data.scenes[SCENE]; dg = _dg(); allo, outside = set(), set()
    for o in sc.objects:
        if o.type not in ('MESH', 'CURVE', 'FONT') or o.get("layer") in ("light", "cam", "items") or _in_bag(o): continue     # "front" parts of the counter are part of the jpg
        ev = o.evaluated_get(dg); ys = [(ev.matrix_world @ Vector(c)).y for c in ev.bound_box]
        allo.add(o.name)
        if o.name.startswith("pane") or min(ys) > OUTSIDE_Y: outside.add(o.name)
    return allo, outside

def _backdrop_compose(path):
    import numpy as np
    A = _load(path); h, w = A.shape[:2]; al = A[..., 3]
    x0, y0 = int(math.floor(WIN_RECT[0] * w)), int(math.floor(WIN_RECT[1] * h))
    x1, y1 = int(math.ceil(WIN_RECT[2] * w)), int(math.ceil(WIN_RECT[3] * h))
    inside = al[y0:y1, x0:x1]
    st = dict(size=[w, h], window_px=[x0, y0, x1, y1], window_px_count=int(inside.size),
              transparent_in_window=int((inside < .5).sum()), fully_transparent_in_window=int((inside <= .002).sum()),
              transparent_outside_window=int((al < .5).sum() - (inside < .5).sum()))
    st["transparent_in_window_pct"] = round(100. * st["transparent_in_window"] / st["window_px_count"], 2)
    jpg = _load(os.path.join(GAME, "delivery_backdrop.jpg"))
    d = np.abs(A[..., :3] - jpg[..., :3]).mean(axis=2)[al > .999]
    st["rgb_vs_jpg_mean_abs"] = round(float(d.mean()), 5); st["rgb_vs_jpg_p99_abs"] = round(float(np.percentile(d, 99)), 5)
    _save(A, BACKDROP_PNG)
    # window sheen: only where the camera sees the street through the panes (alpha 0 region inside the window rect)
    X = (np.arange(w) + .5) / w; Y = (np.arange(h) + .5) / h; X, Y = np.meshgrid(X, Y)
    rect = (X >= WIN_RECT[0]) & (X <= WIN_RECT[2]) & (Y >= WIN_RECT[1]) & (Y <= WIN_RECT[3])
    hole = np.clip(1 - 2 * al, 0, 1) * rect
    t = X - .55 * Y                                              # diagonal coordinate: streaks lean like a reflection
    streak = sum(wt * np.exp(-((t - c) / s) ** 2) for c, wt, s in ((-.10, 1., .010), (-.02, .6, .006), (.06, .8, .012), (.16, .35, .008)))
    G = np.zeros_like(A); G[..., :3] = 1.; G[..., 3] = (.04 + .09 * np.clip(streak, 0, 1)) * hole
    _save(G, GLASS_PNG)
    st["glass_alpha_max"] = round(float(G[..., 3].max()), 4)
    st["files"] = {os.path.basename(BACKDROP_PNG): os.path.getsize(BACKDROP_PNG), os.path.basename(GLASS_PNG): os.path.getsize(GLASS_PNG)}
    return st

def export_backdrop_windowless():
    """Renders the static backdrop with the street + glass panes invisible to the camera (their light and shadows stay),
    so the window opening is transparent.  Timer driven; the MCP call returns at once."""
    import time, traceback
    os.makedirs(RAW, exist_ok=True); os.makedirs(GAME, exist_ok=True)
    path = _raw("backdrop_windowless"); state = dict(i=0, t0=time.time(), changed=[])
    def restore():
        for n in state["changed"]:
            o = bpy.data.objects.get(n)
            if o is not None: o.visible_camera = True
        state["changed"] = []
    def tick():
        try:
            if state["i"] == 0:
                allo, outside = _backdrop_sets(); _vis(allo, ())
                for n in outside: bpy.data.objects[n].visible_camera = False
                state["changed"] = sorted(outside); state["i"] = 1
                _bstatus(state="rendering", static=len(allo), through_window=len(outside)); return .3
            if state["i"] == 1:
                _render(path, None, True); state["i"] = 2; return .3
            if state["i"] == 2:
                restore(); st = _backdrop_compose(path)
                for o in bpy.data.scenes[SCENE].objects: o.is_holdout = False
                _bstatus(state="done", secs=round(time.time() - state["t0"]), **st); return None
        except Exception:
            restore(); _bstatus(state="error", error=traceback.format_exc()); return None
    _bstatus(state="queued"); bpy.app.timers.register(tick, first_interval=.5)
    return "queued"
