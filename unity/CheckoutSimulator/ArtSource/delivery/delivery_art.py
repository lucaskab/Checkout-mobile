def _kraft_flap_y(z):
    """y (bag local) of the outer face of the folded flap on the closed kraft bag at height z."""
    D, H = BAG["D"], BAG["H"]; v = z / H; t = min(1., max(0., (v - .78) / .22)); p = t * t * (3 - 2 * t)
    return -D / 2 + z * math.tan(rad(4)) + p * (D / 2 - .006 - math.sin(rad(4)) * H) - .006 - .004 * (1 - (z - (H + .002 - KRAFT_FLAP)) / KRAFT_FLAP) - .0015

