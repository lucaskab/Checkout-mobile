def _shadow(full, base, layer_alpha, border=None, thr=.035, cap=.85, feather=40):
    """alpha film of the darkening the bag adds to its surroundings (only where the bag itself is not), faded out
    `feather` px before the edges of the render border."""
    import numpy as np
    L = lambda a: a[..., 0] * .2126 + a[..., 1] * .7152 + a[..., 2] * .0722
    s = 1 - L(full) / np.maximum(L(base), 1e-3)
    s = np.clip((s - thr) / (1 - thr), 0, cap)
    s *= (full[..., 3] > .995) * (layer_alpha < .015)
    if border is not None:
        h, w = s.shape; x0, y0, x1, y1 = border[0] * w, border[1] * h, border[2] * w, border[3] * h
        xs = np.arange(w)[None, :] + .5; ys = np.arange(h)[:, None] + .5       # rows bottom-up (bpy pixel order)
        d = np.minimum(np.minimum(xs - x0, x1 - xs), np.minimum(ys - y0, y1 - ys))
        f = np.clip(d / feather, 0, 1); s *= f * f * (3 - 2 * f)
    return s

def _over_shadow(layer, sh):
    import numpy as np
    a = layer[..., 3]; out = np.zeros_like(layer); oa = a + sh * (1 - a)
    out[..., :3] = layer[..., :3] * (a / np.maximum(oa, 1e-6))[..., None]; out[..., 3] = oa; return out

